"""Nested OOF image-report co-teaching with image-only gold evaluation.

For every outer seed, teacher predictions for the outer training partition are
generated by five fixed-epoch inner models that never see their held-out report
group. Conservative corrections and reliability weights are computed without
organizer labels. Gold studies remain final evaluation-only.
"""

from sklearn.model_selection import GroupKFold


TEACHER_EPOCHS = 12
CORRECTION_ALPHA = 0.15
TEACHER_CONFIDENCE_GATE = 0.80
DISAGREEMENT_GATE = 0.35


def normalized_reports(series):
    return (series.fillna("").astype(str).str.lower()
            .str.replace(r"\s+", " ", regex=True).str.strip())


def report_groups(series):
    return np.asarray([hashlib.sha256(text.encode()).hexdigest()[:24]
                       for text in normalized_reports(series)])


def fixed_teacher(features, masks, labels, train_index, heldout_index, seed):
    """Fixed epochs: held-out labels never affect stopping or selection."""
    seed_all(seed)
    model = AttentionHead().to(DEVICE)
    optimizer = torch.optim.AdamW(model.parameters(), lr=2e-4, weight_decay=1e-3)
    dataset = TensorDataset(
        torch.from_numpy(features[train_index]),
        torch.from_numpy(masks[train_index]),
        torch.from_numpy(labels[train_index]),
    )
    loader = DataLoader(dataset, batch_size=64, shuffle=True,
                        generator=torch.Generator().manual_seed(seed))
    for _ in range(TEACHER_EPOCHS):
        model.train()
        for x, mask, target in loader:
            x, mask, target = x.to(DEVICE), mask.to(DEVICE), target.to(DEVICE)
            optimizer.zero_grad(set_to_none=True)
            loss = torch.nn.functional.binary_cross_entropy_with_logits(
                model(x, mask), target.float()
            )
            loss.backward(); optimizer.step()
    prediction = predict(model, features, masks, heldout_index)
    del model; torch.cuda.empty_cache()
    return prediction


def nested_oof_teacher(features, masks, labels, outer_train, groups, seed):
    local_groups = groups[outer_train]
    splitter = GroupKFold(5)
    prediction = np.full((len(features), len(TARGETS)), np.nan, np.float32)
    fold_audit = []
    for fold, (inner_train_local, heldout_local) in enumerate(
        splitter.split(outer_train, groups=local_groups)
    ):
        inner_train = outer_train[inner_train_local]
        heldout = outer_train[heldout_local]
        if set(groups[inner_train]).intersection(groups[heldout]):
            raise RuntimeError(f"inner report-group leakage in fold {fold}")
        prediction[heldout] = fixed_teacher(
            features, masks, labels, inner_train, heldout,
            seed + 1000 + fold,
        )
        fold_audit.append({
            "fold": fold, "train_studies": int(len(inner_train)),
            "heldout_studies": int(len(heldout)),
            "heldout_groups": int(len(np.unique(groups[heldout]))),
        })
    if not np.isfinite(prediction[outer_train]).all():
        raise RuntimeError("incomplete nested OOF teacher predictions")
    return prediction, fold_audit


def correction_contract(report_target, image_oof):
    report_certainty = np.clip(2.0*np.abs(report_target-.5), 0, 1)
    image_confidence = np.clip(2.0*np.abs(image_oof-.5), 0, 1)
    disagreement = np.abs(report_target-image_oof)
    agreement = 1.0-disagreement
    correct = ((image_confidence >= TEACHER_CONFIDENCE_GATE)
               & (disagreement >= DISAGREEMENT_GATE))
    corrected = report_target.copy()
    corrected[correct] = ((1.0-CORRECTION_ALPHA)*report_target[correct]
                          + CORRECTION_ALPHA*image_oof[correct])
    reliability = (.25 + .75*(.50*report_certainty
                              + .30*agreement
                              + .20*image_confidence)).astype(np.float32)
    # Strong cross-modal disagreement is uncertain even when both sources are
    # individually confident. Downweight; never discard a target entirely.
    reliability[disagreement >= DISAGREEMENT_GATE] *= .65
    reliability = np.clip(reliability, .15, 1.0)
    return corrected.astype(np.float32), reliability, {
        "corrected_fraction": float(correct.mean()),
        "mean_reliability": float(reliability.mean()),
        "low_reliability_fraction": float((reliability < .5).mean()),
        "mean_disagreement": float(disagreement.mean()),
    }


def train_student(features, masks, targets, weights, train_index,
                  validation_index, validation_labels, seed):
    seed_all(seed)
    model = AttentionHead().to(DEVICE)
    optimizer = torch.optim.AdamW(model.parameters(), lr=2e-4, weight_decay=1e-3)
    dataset = TensorDataset(
        torch.from_numpy(features[train_index]),
        torch.from_numpy(masks[train_index]),
        torch.from_numpy(targets[train_index]),
        torch.from_numpy(weights[train_index]),
    )
    loader = DataLoader(dataset, batch_size=64, shuffle=True,
                        generator=torch.Generator().manual_seed(seed))
    best_state, best_score = None, -1.0
    for _ in range(20):
        model.train()
        for x, mask, target, weight in loader:
            x, mask = x.to(DEVICE), mask.to(DEVICE)
            target, weight = target.to(DEVICE), weight.to(DEVICE)
            optimizer.zero_grad(set_to_none=True)
            raw = torch.nn.functional.binary_cross_entropy_with_logits(
                model(x, mask), target.float(), reduction="none"
            )
            loss = (raw*weight).sum()/weight.sum().clamp_min(1)
            loss.backward(); optimizer.step()
        validation_prediction = predict(
            model, features, masks, validation_index
        )
        score = macro_auc(validation_labels[validation_index],
                          validation_prediction)
        if score > best_score:
            best_score = score
            best_state = {key: value.detach().cpu().clone()
                          for key, value in model.state_dict().items()}
    model.load_state_dict(best_state)
    prediction = predict(model, features, masks, np.arange(len(features)))
    del model; torch.cuda.empty_cache()
    return prediction, float(best_score)


def coteaching_main():
    if DEVICE.type != "cuda": raise RuntimeError("co-teaching validation requires GPU")
    root = competition_root()
    train = pd.read_csv(root/"train.csv", dtype={"StudyInstanceUID": str})
    gold = train[TARGETS].notna().all(axis=1).to_numpy()
    if int(gold.sum()) != 58: raise RuntimeError(f"expected 58 gold studies, found {gold.sum()}")
    gold_index = np.flatnonzero(gold); nongold = np.flatnonzero(~gold)
    weak = pd.read_csv(unique_input("llm_labels_v4_blend.csv"),
                       dtype={"StudyInstanceUID": str})
    aligned = train[["StudyInstanceUID"]].merge(
        weak, on="StudyInstanceUID", how="left", validate="one_to_one"
    )
    labels = aligned[TARGETS].to_numpy(np.float32)
    if not np.isfinite(labels).all(): raise RuntimeError("weak labels incomplete")

    package = np.load(unique_input("incumbent_radimagenet_features.npz"),
                      allow_pickle=False)
    if package["ids"].astype(str).tolist() != train.StudyInstanceUID.tolist():
        raise RuntimeError("feature study identity/order drift")
    features, masks = package["features"], package["masks"]
    if features.shape != (4407, len(SLOTS)*N_SLICE, TOKEN_DIM):
        raise RuntimeError(f"feature shape drift: {features.shape}")
    if str(package["encoder_sha256"]) != RAD_SHA:
        raise RuntimeError("feature encoder hash drift")

    groups = report_groups(train["Report"])
    y_gold = train.loc[gold, TARGETS].to_numpy(float)
    results, control_gold, student_gold, correction_audits = [], [], [], []
    for seed in SEEDS:
        unique_groups = np.unique(groups[nongold])
        shuffled = np.random.default_rng(seed).permutation(unique_groups)
        validation_groups = set(shuffled[:max(1, int(.10*len(shuffled)))])
        validation_index = nongold[np.asarray(
            [group in validation_groups for group in groups[nongold]]
        )]
        outer_train = nongold[np.asarray(
            [group not in validation_groups for group in groups[nongold]]
        )]
        if set(groups[outer_train]).intersection(groups[validation_index]):
            raise RuntimeError("outer report-group leakage")
        image_oof, fold_audit = nested_oof_teacher(
            features, masks, labels, outer_train, groups, seed
        )
        corrected_train, reliability_train, correction_audit = correction_contract(
            labels[outer_train], image_oof[outer_train]
        )
        corrected = labels.copy(); reliability = np.ones_like(labels, np.float32)
        corrected[outer_train] = corrected_train
        reliability[outer_train] = reliability_train
        correction_audits.append({
            "seed": seed, "outer_train_studies": int(len(outer_train)),
            "weak_validation_studies": int(len(validation_index)),
            "inner_folds": fold_audit, **correction_audit,
        })
        control, control_weak = train_student(
            features, masks, labels, np.ones_like(labels, np.float32),
            outer_train, validation_index, labels, seed
        )
        student, student_weak = train_student(
            features, masks, corrected, reliability,
            outer_train, validation_index, labels, seed
        )
        control_auc = macro_auc(y_gold, control[gold_index])
        student_auc = macro_auc(y_gold, student[gold_index])
        results.append({
            "seed": seed,
            "control_weak_validation_auc": control_weak,
            "student_weak_validation_auc": student_weak,
            "control_gold_auc": control_auc,
            "student_gold_auc": student_auc,
            "delta": student_auc-control_auc,
        })
        control_gold.append(control[gold_index]); student_gold.append(student[gold_index])
        log(f"seed {seed}: nested OOF co-teaching delta {student_auc-control_auc:+.6f}")
    control_mean = np.mean(control_gold, axis=0)
    student_mean = np.mean(student_gold, axis=0)
    control_auc = macro_auc(y_gold, control_mean)
    student_auc = macro_auc(y_gold, student_mean)
    bootstrap = paired_bootstrap(y_gold, control_mean, student_mean)
    deltas = np.asarray([record["delta"] for record in results])
    gate = {
        "delta_at_least_0_005": student_auc-control_auc >= .005,
        "positive_seeds_at_least_4": int((deltas > 0).sum()) >= 4,
        "bootstrap_p_at_least_0_95": bootstrap["p_improve"] >= .95,
        "bootstrap_q025_positive": bootstrap["q025"] > 0,
    }
    report = {
        "contract": "nested report-group OOF co-teaching; image-only gold evaluation",
        "encoder": "RadImageNet ResNet-50", "encoder_sha256": RAD_SHA,
        "feature_source": "rsna-knee-report-image-cross-supervision v1 authenticated output",
        "weak_labels": "stevenleehans llm_labels_v4_blend.csv",
        "teacher_epochs": TEACHER_EPOCHS,
        "correction_alpha": CORRECTION_ALPHA,
        "teacher_confidence_gate": TEACHER_CONFIDENCE_GATE,
        "disagreement_gate": DISAGREEMENT_GATE,
        "correction_audits": correction_audits,
        "gold_fit_count": 0, "gold_oof_count": 0,
        "gold_evaluation_count": 58,
        "seeds": results,
        "ensemble": {"control_gold_auc": control_auc,
                     "student_gold_auc": student_auc,
                     "delta": student_auc-control_auc},
        "bootstrap": bootstrap, "gate": gate,
        "passed": bool(all(gate.values())), "submission_created": False,
    }
    Path("/kaggle/working/oof_coteaching_validation_report.json").write_text(
        json.dumps(report, indent=2)+"\n", encoding="utf-8"
    )
    print(json.dumps(report, indent=2))


coteaching_main()
